    private void btnParaleloActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnParaleloActionPerformed
        // Quantidade de threads escolhida pelo usuário
        int qtdThreads = Integer.parseInt(
                cbxThreads.getSelectedItem().toString());

        log("");
        log("===== EXECUÇÃO PARALELA =====");
        log("Quantidade de threads: " + qtdThreads);
        
        // Início da medição do tempo total
        long tempoInicio = System.nanoTime();

        // Divide o vetor conforme a quantidade de threads
        int tamanhoParte = vetor.length / qtdThreads;

        // Guarda as tarefas para obter os resultados depois
        ArrayList<Tarefa> tarefas = new ArrayList<>();

        // Cria o pool com a quantidade de threads que o usuário solicitou
        ExecutorService executor = Executors.newFixedThreadPool(qtdThreads);

        for (int i = 0; i < qtdThreads; i++) {
            int inicio = i * tamanhoParte;            
            int fim = (i == qtdThreads - 1) ? vetor.length : inicio + tamanhoParte; //última thread fica com o resto do vetor

            // Cria a tarefa responsável por uma parte do vetor
            Tarefa tarefa = new Tarefa(vetor, inicio, fim);

            tarefas.add(tarefa);

            // Envia a tarefa para o Pool.
            // Uma das threads disponíveis será responsável por executá-la.
            executor.submit(tarefa);
        }

        // Não serão enviadas novas tarefas ao pool
        executor.shutdown();

        // Aguarda o término e apresenta os resultados
        esperarFim(executor, tarefas, tempoInicio);
    }//GEN-LAST:event_btnParaleloActionPerformed

    private void btnSequencialActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSequencialActionPerformed
        long inicio = System.nanoTime();

        long soma = 0;

        for (int i = 0; i < vetor.length; i++) {
            soma += (long) vetor[i]*vetor[i]*vetor[i]; //soma do cubo do de cada elemento do vetor 
        }

        // Tempo decorrido convertido de nano para microssegundos
        long tempo = (System.nanoTime() - inicio) / 1000;

        log("");
        log("===== EXECUÇÃO SEQUENCIAL =====");
        log("Soma total: " + soma);
        log("Tempo: " + tempo + " µs");
    }//GEN-LAST:event_btnSequencialActionPerformed

