    private void esperarFim(ExecutorService executor, ArrayList<Tarefa> tarefas,long tempoInicio) {
        // Cria uma thread apenas para aguardar o término do Pool,
        // evitando travar a interface gráfica.
        Thread threadEspera = new Thread(new Runnable() {
           @Override
            public void run() {
                try {
                    // Aguarda todas as tarefas enviadas ao Pool terminarem.
                    // O shutdown() já foi chamado antes deste método.
                    executor.awaitTermination(Long.MAX_VALUE,TimeUnit.NANOSECONDS);
                } catch (InterruptedException e) {
                    System.out.println("Erro ao aguardar as tarefas.");
                }

                long somaTotal = 0;
                log("");

                // Todas as tarefas já terminaram. A seguir vem a consulta dos resultados.
                for (int i = 0; i < tarefas.size(); i++) {
                    Tarefa tarefa = tarefas.get(i);                    
                    log("Tarefa " + (i + 1));
                    log("Índices: " + tarefa.getInicio() + " até " + (tarefa.getFim() - 1));
                    log("Soma parcial: "+ tarefa.getSomaParcial());
                    log("Tempo: " + tarefa.getTempo() + " µs");
                    log("");

                    // Soma os resultados parciais
                    somaTotal += tarefa.getSomaParcial();
                }

                // Calcula o tempo total da execução paralela
                long tempoTotal = (System.nanoTime()- tempoInicio)/1000; //converte de nano para microsegundos
                log("Soma total: " + somaTotal);
                log("Tempo total paralelo: " + tempoTotal + " µs");
            }
        });

        threadEspera.start();
    }


